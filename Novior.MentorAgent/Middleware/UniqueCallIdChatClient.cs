using System.Runtime.CompilerServices;

namespace Novior.MentorAgent.Middleware;

/// <summary>
/// Every call of a model response gets an id of its own before the function-invoking client sees it (BUG-225). A call
/// whose id the response already gave to an earlier call, or that the conversation sent to the model already holds,
/// is given <c>&lt;id&gt;_n</c>, the first <c>n</c> from 2 that neither uses: three calls <c>w</c> become <c>w</c>,
/// <c>w_2</c> and <c>w_3</c>, and with <c>w_2</c> already in the conversation <c>w</c>, <c>w_3</c> and <c>w_4</c>.
///
/// <para>
/// The function-invoking client keys its approval requests by the call id. Given two calls of one id in Native mode
/// it threw "An item with the same key has already been added" when they were answered; the stored conversation ended
/// on both requests, and every later turn failed closing them, until the conversation was reset. In Blocking mode
/// both calls ran and both results went back to the model under one id, which a provider may refuse. The result of a
/// call takes the id of the call it answers, so the renamed call, its approval request and its result agree with no
/// more work.
/// </para>
///
/// <para>
/// Next to the provider's client, under every wrapper of the pipeline, so that everything above it sees each call
/// once. The provider adapters of Microsoft.Extensions.AI hand over a call whole, in one update, also when the wire
/// streams it in pieces. A renamed call is a copy without its raw representation: an adapter that sends the raw item
/// back would send the old id. Without a repeated id the response is passed on as it came, the same instances.
/// </para>
///
/// <para>
/// With service-managed history (<c>UseServiceManagedHistory</c>) nothing is renamed: the service holds the calls
/// under the ids it generated, and a result sent under another id answers none of them. A warning says so, once.
/// Those ids are generated by the service, so a repeated one is not expected there.
/// </para>
///
/// <para>
/// On path B (<c>MentorOptions.Agent</c>) the agent and its chat client are the host's. The client factory of a run,
/// where MentorAgent adds its per-request clients, decorates the agent's client outside its function-invoking client:
/// a call reaches it already run, under the id the model gave it.
/// </para>
/// </summary>
internal sealed class UniqueCallIdChatClient(IChatClient innerClient, bool rename, ILogger logger)
    : DelegatingChatClient(innerClient)
{
    private readonly bool _rename = rename;
    private int _renamedBefore;
    private int _keptBefore;

    public override async Task<ChatResponse> GetResponseAsync(
        IEnumerable<ChatMessage> messages,
        ChatOptions? options = null,
        CancellationToken cancellationToken = default)
    {
        var sent = messages as IReadOnlyCollection<ChatMessage> ?? [.. messages];
        var response = await base.GetResponseAsync(sent, options, cancellationToken);

        var ids = new Ids(sent, this);
        foreach (var message in response.Messages)
            ids.MakeUnique(message.Contents);
        return response;
    }

    public override async IAsyncEnumerable<ChatResponseUpdate> GetStreamingResponseAsync(
        IEnumerable<ChatMessage> messages,
        ChatOptions? options = null,
        [EnumeratorCancellation] CancellationToken cancellationToken = default)
    {
        var sent = messages as IReadOnlyCollection<ChatMessage> ?? [.. messages];
        var ids = new Ids(sent, this);
        await foreach (var update in base.GetStreamingResponseAsync(sent, options, cancellationToken))
        {
            ids.MakeUnique(update.Contents);
            yield return update;
        }
    }

    /// <summary>The ids one response may not repeat: the conversation's, read at its first call, and its own so far.</summary>
    private sealed class Ids(IEnumerable<ChatMessage> sent, UniqueCallIdChatClient owner)
    {
        private HashSet<string>? _taken;

        public void MakeUnique(IList<AIContent> contents)
        {
            for (var i = 0; i < contents.Count; i++)
            {
                // The calls the function-invoking client runs. A hosted tool's call is the service's.
                if (contents[i] is not FunctionCallContent call || call.GetType() != typeof(FunctionCallContent)) continue;

                _taken ??= Conversation(sent);
                if (_taken.Add(call.CallId)) continue;

                if (!owner._rename)
                {
                    owner.Kept(call.CallId);
                    continue;
                }

                var renamed = Copy(call, Next(call.CallId));
                _taken.Add(renamed.CallId);
                contents[i] = renamed;
                owner.Renamed(call.CallId, renamed.CallId);
            }
        }

        /// <summary>The first <c>&lt;id&gt;_n</c>, from 2, that neither the conversation nor the response uses.</summary>
        private string Next(string id)
        {
            var n = 2;
            while (_taken!.Contains($"{id}_{n}")) n++;
            return $"{id}_{n}";
        }

        private static HashSet<string> Conversation(IEnumerable<ChatMessage> sent)
        {
            var taken = new HashSet<string>(StringComparer.Ordinal);
            foreach (var message in sent)
                foreach (var content in message.Contents)
                    switch (content)
                    {
                        case FunctionCallContent c: taken.Add(c.CallId); break;
                        case FunctionResultContent r: taken.Add(r.CallId); break;
                    }
            return taken;
        }
    }

    /// <summary>The call under <paramref name="id"/>, without the raw representation, which carries the old id.</summary>
    private static FunctionCallContent Copy(FunctionCallContent call, string id) => new(id, call.Name, call.Arguments)
    {
        AdditionalProperties = call.AdditionalProperties,
        Annotations = call.Annotations,
        Exception = call.Exception,
        InformationalOnly = call.InformationalOnly,
    };

    private void Renamed(string id, string renamed)
    {
        if (Interlocked.Exchange(ref _renamedBefore, 1) == 0)
            logger.LogWarning(
                "[MentorAgent] The model gave two calls the same id ({Id}): the later one is now {Renamed}, so that " +
                "each call has an answer of its own (BUG-225).", id, renamed);
        else
            logger.LogDebug("[MentorAgent] Call id {Id} repeated by the model: renamed {Renamed}.", id, renamed);
    }

    private void Kept(string id)
    {
        if (Interlocked.Exchange(ref _keptBefore, 1) == 0)
            logger.LogWarning(
                "[MentorAgent] The model gave two calls the same id ({Id}). With service-managed history the service " +
                "holds the calls under the ids it generated, so they are not renamed, and the turn may fail (BUG-225).",
                id);
    }
}
